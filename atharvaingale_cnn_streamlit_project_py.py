import streamlit as st

# User Inputs
name = st.text_input("Enter Student Name")
m1 = st.number_input("Subject 1 Marks", min_value=0, max_value=100, value=75)
m2 = st.number_input("Subject 2 Marks", min_value=0, max_value=100, value=80)
m3 = st.number_input("Subject 3 Marks", min_value=0, max_value=100, value=70)
m4 = st.number_input("Subject 4 Marks", min_value=0, max_value=100, value=85)
m5 = st.number_input("Subject 5 Marks", min_value=0, max_value=100, value=90)

# Processing & Output
if st.button("Calculate Result"):
    if name.strip() == "":
        st.warning("Please enter your name first.")
    else:
        total = m1 + m2 + m3 + m4 + m5
        percentage = (total / 500) * 100

        if percentage >= 75:
            grade = "Distinction"
        elif percentage >= 60:
            grade = "First Class"
        elif percentage >= 40:
            grade = "Pass"
        else:
            grade = "Fail"

        st.success(f"Result for {name}")
        st.write(f"**Total Marks:** {total} / 500")
        st.write(f"**Percentage:** {percentage:.2f}%")
        st.write(f"**Grade:** {grade}")

