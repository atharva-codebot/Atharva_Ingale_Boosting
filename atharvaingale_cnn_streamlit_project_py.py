import tensorflow as tf

(X_train, y_train), (X_test, y_test) = tf.keras.datasets.cifar10.load_data()
y_train = y_train.flatten()
y_test = y_test.flatten()

class_names = [
    'airplane', 'automobile', 'bird', 'cat', 'deer',
    'dog', 'frog', 'horse', 'ship', 'truck'
]

print("X_train shape:", X_train.shape)
print("X_test shape:", X_test.shape)

import matplotlib.pyplot as plt

plt.figure(figsize=(8, 4))
for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_train[i])
    plt.title(class_names[y_train[i]])
    plt.axis('off')
plt.tight_layout()
plt.show()

X_train = X_train / 255.0
X_test = X_test / 255.0

from tensorflow.keras import layers, models

model = models.Sequential([
    layers.Input(shape=(32, 32, 3)),
    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dense(10, activation='softmax')
])

model.summary()

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

history = model.fit(X_train, y_train, epochs=5, validation_data=(X_test, y_test))

plt.figure(figsize=(10, 4))

plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'], label='Train Accuracy')
plt.plot(history.history['val_accuracy'], label='Val Accuracy')
plt.title('Training & Validation Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend()

plt.subplot(1, 2, 2)
plt.plot(history.history['loss'], label='Train Loss')
plt.plot(history.history['val_loss'], label='Val Loss')
plt.title('Training & Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()

plt.tight_layout()
plt.show()

import numpy as np

test_loss, test_acc = model.evaluate(X_test, y_test)
print(f"Test accuracy: {test_acc:.4f}")

predictions = model.predict(X_test)
pred_labels = np.argmax(predictions, axis=1)

correct = np.where(pred_labels == y_test)[0]
incorrect = np.where(pred_labels != y_test)[0]

plt.figure(figsize=(10, 4))
for i in range(5):
    idx_c = correct[i]
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_test[idx_c])
    plt.title(f"True: {class_names[y_test[idx_c]]}\nPred: {class_names[pred_labels[idx_c]]}", color='green', fontsize=8)
    plt.axis('off')

    idx_w = incorrect[i]
    plt.subplot(2, 5, i + 6)
    plt.imshow(X_test[idx_w])
    plt.title(f"True: {class_names[y_test[idx_w]]}\nPred: {class_names[pred_labels[idx_w]]}", color='red', fontsize=8)
    plt.axis('off')

plt.tight_layout()
plt.show()

